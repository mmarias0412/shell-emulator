"""Разбор строки ввода на команду и аргументы."""


def parse(line):
    """Делит строку по пробелам.

    Возвращает пару (команда, список_аргументов).
    Для пустой строки команда равна None.
    """
    parts = line.split()
    if not parts:
        return None, []
    return parts[0], parts[1:]
